import hashlib, time
import requests
import pandas as pd
from datetime import datetime
from google.colab import files

# Configuración
API_KEY = "PEGA_AQUI_TU_CLAVE"
MAX_POR_VIDEO = 1500
LIMITE_UNIDADES = 2000               # freno de seguridad (la cuota gratis es 10.000 al día)

VIDEOS = [
    ("IIyUWDp8pRE", "carga"), ("S5wDtAQIiHI", "carga"),
    ("3X6taeC-x7U", "carga"), ("uOJRwnAtSjg", "carga"),
    ("41cyBLOZeMI", "motos"), ("1jY69g9j0bI", "motos"), ("sEgXFtSipkg", "motos"),
    ("IFh9zbJY2oM", "motos"), ("Ju_42thsgFw", "motos"), ("F1JlN_dRDKs", "motos"),
    ("JQJJjahhZ2A", "parque_control"), ("Qp8ZlD4O0Dk", "parque_control"),
    ("aR-mgVmUSys", "parque_control"), ("J7KUrioAWgU", "parque_control"),
    ("a1PRXdJSptA", "parque_control"),
    ("ZssODcZxkOw", "pasajeros"), ("Rzzrh-hZ_h8", "pasajeros"),
    ("ceLoxBwSeX8", "justicia_conducta"), ("9fn2NfMpsUI", "justicia_conducta"),
    ("W_tMFY1AhxQ", "sabana_corredores"), ("QM1GijSo2Wg", "sabana_corredores"),
]

def anonimizar(snippet):
    autor = (snippet.get("authorChannelId") or {}).get("value", "")
    return hashlib.sha256(("etapa6" + autor).encode()).hexdigest()[:16] if autor else ""

comentarios, resumen = [], []
unidades = 0

for VIDEO_ID, EJE in VIDEOS:
    pagina, hilos, estado = None, 0, "ok"

    while hilos < MAX_POR_VIDEO and unidades < LIMITE_UNIDADES:
        parametros = {
            "key": API_KEY,
            "part": "snippet,replies",
            "videoId": VIDEO_ID,
            "maxResults": 100,
            "textFormat": "plainText",
            "order": "time"
        }
        if pagina:
            parametros["pageToken"] = pagina

        respuesta = requests.get(
            "https://www.googleapis.com/youtube/v3/commentThreads",
            params=parametros,
            timeout=30
        )
        unidades += 1
        datos = respuesta.json()

        if respuesta.status_code != 200:
            estado = "Error: " + str(datos.get("error", {}).get("message"))
            break

        for elemento in datos.get("items", []):
            hilos += 1
            principal = elemento["snippet"]["topLevelComment"]
            todos = [(principal, 0)] + [(r, 1) for r in elemento.get("replies", {}).get("comments", [])]
            for c, es_respuesta in todos:
                s = c["snippet"]
                comentarios.append({
                    "comentario_id": c["id"],
                    "hilo_id": elemento["id"],
                    "video_id": VIDEO_ID,
                    "eje": EJE,
                    "es_respuesta": es_respuesta,
                    "autor_hash": anonimizar(s),
                    "texto": s["textOriginal"],
                    "likes": s["likeCount"],
                    "publicado": s["publishedAt"][:19]
                })

        pagina = datos.get("nextPageToken")
        if not pagina:
            break
        time.sleep(0.2)

    n = sum(1 for c in comentarios if c["video_id"] == VIDEO_ID)
    resumen.append({"video_id": VIDEO_ID, "eje": EJE,
                    "enlace": f"https://www.youtube.com/watch?v={VIDEO_ID}",
                    "comentarios_extraidos": n, "estado": estado})
    print(f"{VIDEO_ID:<12} {EJE:<18} {n:>5} comentarios · {estado}")

# Guardar en Colab y descargar
if comentarios:
    df = pd.DataFrame(comentarios)
    res = pd.DataFrame(resumen)
    res["fecha_extraccion"] = datetime.now().strftime("%Y-%m-%d %H:%M")

    df.to_csv("/content/comentarios_crudos.csv", index=False, encoding="utf-8-sig")
    res.to_csv("/content/videos_seleccionados.csv", index=False, encoding="utf-8-sig")

    print(f"\nComentarios guardados: {len(df)} · unidades usadas ≈ {unidades} de 10.000")
